// Generates examples/customer_satisfaction.csv: a synthetic customer-satisfaction survey
// (7-point Likert items) from a known structural model. Deterministic (seeded).
'use strict';
const fs = require('fs'), path = require('path');
const E = require('../js/engine.js');
const rand = E.rng(2026);
const gauss = () => { let u = 0, v = 0; while (!u) u = rand(); v = rand(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v); };
const N = 300;
const blocks = {
  IMAG: [0.78, 0.74, 0.70, 0.82, 0.66], EXPE: [0.80, 0.75, 0.70], QUAL: [0.82, 0.79, 0.74, 0.77],
  VAL: [0.85, 0.80, 0.76], SAT: [0.88, 0.84, 0.80], LOY: [0.86, 0.80, 0.72]
};
const rows = [];
for (let i = 0; i < N; i++) {
  const female = rand() < 0.5;
  const e = () => gauss();
  const IMAG = e();
  const EXPE = 0.50 * IMAG + Math.sqrt(1 - 0.25) * e();
  const QUAL = 0.55 * EXPE + Math.sqrt(1 - 0.3025) * e();
  const VAL = 0.20 * EXPE + 0.50 * QUAL + 0.75 * e();
  const sv = female ? 0.45 : 0.20; // group difference for MGA
  const SAT = 0.20 * IMAG + 0.05 * EXPE + 0.25 * QUAL + sv * VAL + 0.6 * e();
  const ly = female ? 0.35 : 0.55;
  const LOY = 0.25 * IMAG + ly * SAT + 0.65 * e();
  const lat = { IMAG, EXPE, QUAL, VAL, SAT, LOY };
  const age = Math.round(22 + rand() * 40);
  const row = { id: i + 1, gender: female ? 'female' : 'male', age };
  for (const [k, lam] of Object.entries(blocks)) {
    const z = lat[k] / 1.2;
    lam.forEach((l, q) => {
      const x = l * z + Math.sqrt(1 - l * l) * gauss();
      let v = Math.round(4.6 + 1.25 * x); v = Math.max(1, Math.min(7, v));
      row[k.toLowerCase() + '_' + (q + 1)] = rand() < 0.006 ? '' : v;
    });
  }
  rows.push(row);
}
const names = Object.keys(rows[0]);
const csv = [names.join(',')].concat(rows.map(r => names.map(n => r[n]).join(','))).join('\n') + '\n';
fs.writeFileSync(path.join(__dirname, '..', 'examples', 'customer_satisfaction.csv'), csv);
console.log('rows', rows.length, 'cols', names.length);
// Embedded copy so the example also loads when index.html is opened from disk (file://).
const model = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'examples', 'customer_satisfaction.model.json'), 'utf8'));
fs.writeFileSync(path.join(__dirname, '..', 'js', 'example-data.js'),
  '/* Generated by tools/make_example.js – do not edit. */\nwindow.YP_EXAMPLE = ' + JSON.stringify({ csv, model }) + ';\n');
